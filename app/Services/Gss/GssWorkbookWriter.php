<?php

declare(strict_types=1);

namespace App\Services\Gss;

use Carbon\CarbonInterface;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Shared\Date as ExcelDate;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\Drawing;
use PhpOffice\PhpSpreadsheet\Worksheet\PageSetup;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;

/** Writes GSS sheets into one .xlsx: letterhead, title, workbook headers, area headings, date and peso formats, print setup */
final class GssWorkbookWriter
{
    private const GREEN = '005A36';

    private const LIGHT = 'E8F5EE';

    /** Row where the header starts (row 1 holds the letterhead, rows 2-3 the title, row 4 is blank) */
    public const HEADER_ROW = 5;

    /** The official DA MIMAROPA letterhead, the same one the trip ticket prints */
    private const LETTERHEAD = 'trip-ticket-header.png';

    /** Letterhead height in pixels; a narrower table is widened to fit it */
    private const LETTERHEAD_HEIGHT = 120;

    /** @param list<GssSheet> $sheets */
    public function write(array $sheets, GssScope $scope): string
    {
        $book = new Spreadsheet;
        $book->getDefaultStyle()->getFont()->setName('Calibri')->setSize(10);
        $book->removeSheetByIndex(0);

        foreach ($sheets as $sheet) {
            $this->writeSheet($book->createSheet(), $sheet, $scope);
        }
        $book->setActiveSheetIndex(0);

        $path = $this->tempFile();
        (new Xlsx($book))->save($path);
        $book->disconnectWorksheets();

        return $path;
    }

    private function writeSheet(Worksheet $ws, GssSheet $sheet, GssScope $scope): void
    {
        $ws->setTitle($sheet->title());
        $ws->setShowGridlines(false);
        $headers = $sheet->headers($scope);
        $columns = max(array_map('count', $headers));
        $lastCol = Coordinate::stringFromColumnIndex($columns);

        // Title under the letterhead
        $ws->setCellValue('A2', $sheet->heading($scope));
        $ws->getStyle('A2')->getFont()->setBold(true)->setSize(13)->getColor()->setRGB(self::GREEN);
        $ws->setCellValue('A3', 'General Services Section · '.$scope->label().' · generated by '.$scope->generatedBy.' on '.now()->format('M j, Y g:i A'));
        $ws->getStyle('A3')->getFont()->setItalic(true)->setSize(9)->getColor()->setRGB('64748B');

        // Header rows; with two rows, a blank lower cell merges down and a blank upper cell merges across
        $row = self::HEADER_ROW;
        foreach ($headers as $r => $cells) {
            foreach ($cells as $c => $text) {
                $ws->setCellValueExplicit([$c + 1, $row + $r], $text, DataType::TYPE_STRING);
            }
        }
        if (count($headers) === 2) {
            for ($c = 0; $c < $columns; $c++) {
                $col = Coordinate::stringFromColumnIndex($c + 1);
                if (($headers[1][$c] ?? '') === '' && ($headers[0][$c] ?? '') !== '') {
                    $ws->mergeCells("{$col}{$row}:{$col}".($row + 1));
                }
                if (($headers[0][$c] ?? '') !== '' && ($headers[0][$c + 1] ?? null) === '' && ($headers[1][$c + 1] ?? '') !== '') {
                    $span = $c + 1;
                    while (($headers[0][$span + 1] ?? null) === '' && ($headers[1][$span + 1] ?? '') !== '') {
                        $span++;
                    }
                    $ws->mergeCells("{$col}{$row}:".Coordinate::stringFromColumnIndex($span + 1).$row);
                }
            }
        }
        $headerEnd = $row + count($headers) - 1;
        $ws->getStyle("A{$row}:{$lastCol}{$headerEnd}")->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => self::GREEN]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
        ]);

        $widths = array_fill(0, $columns, 8);
        foreach ($headers as $cells) {
            foreach ($cells as $c => $text) {
                $widths[$c] = max($widths[$c], min(24, mb_strlen($text) + 2));
            }
        }

        $row = $headerEnd + 1;
        $sheetMoney = $sheet->moneyColumns();
        foreach ($sheet->rows($scope) as $item) {
            if (isset($item['group'])) {
                $ws->setCellValueExplicit("A{$row}", (string) $item['group'], DataType::TYPE_STRING);
                $ws->mergeCells("A{$row}:{$lastCol}{$row}");
                $ws->getStyle("A{$row}:{$lastCol}{$row}")->applyFromArray([
                    'font' => ['bold' => true, 'color' => ['rgb' => self::GREEN]],
                    'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => self::LIGHT]],
                ]);
                $row++;

                continue;
            }

            foreach (array_values($item['cells']) as $c => $value) {
                $this->setCell($ws, $c + 1, $row, $value, in_array($c, $item['money'] ?? $sheetMoney, true));
                if (is_string($value) && $value !== '') {
                    $widths[$c] = max($widths[$c] ?? 8, min(45, mb_strlen(strtok($value, "\n")) + 2));
                } elseif ($value instanceof CarbonInterface) {
                    $widths[$c] = max($widths[$c] ?? 8, 13);
                }
            }
            if (! empty($item['bold'])) {
                $ws->getStyle("A{$row}:{$lastCol}{$row}")->getFont()->setBold(true);
            }
            $row++;
        }

        $last = max($headerEnd, $row - 1);
        $ws->getStyle('A'.self::HEADER_ROW.":{$lastCol}{$last}")->getBorders()->getAllBorders()
            ->setBorderStyle(Border::BORDER_THIN)->getColor()->setRGB('94A3B8');
        if ($last > $headerEnd) {
            $ws->getStyle('A'.($headerEnd + 1).":{$lastCol}{$last}")->getAlignment()->setVertical(Alignment::VERTICAL_TOP)->setWrapText(true);
        }
        $this->letterhead($ws, $widths);
        foreach ($widths as $c => $width) {
            $ws->getColumnDimension(Coordinate::stringFromColumnIndex($c + 1))->setWidth($width);
        }

        $ws->freezePane('A'.($headerEnd + 1));
        $ws->getPageSetup()
            ->setOrientation(PageSetup::ORIENTATION_LANDSCAPE)
            ->setPaperSize(PageSetup::PAPERSIZE_LEGAL)
            ->setFitToWidth(1)->setFitToHeight(0)
            ->setRowsToRepeatAtTopByStartAndEnd(self::HEADER_ROW, $headerEnd);
        $ws->getHeaderFooter()->setOddFooter('&L&8'.$sheet->title().' · '.$scope->label().'&R&8Page &P of &N');
    }

    /**
     * The DA MIMAROPA letterhead at A1, where the workbook puts its banner; a table narrower than the
     * letterhead gets wider columns, so the banner prints whole within the page width
     *
     * @param  array<int, float|int>  $widths  column widths in characters, widened when needed
     */
    private function letterhead(Worksheet $ws, array &$widths): void
    {
        $file = public_path(self::LETTERHEAD);
        $size = is_file($file) ? @getimagesize($file) : false;
        if (! $size) {
            return;
        }

        $height = self::LETTERHEAD_HEIGHT;
        $width = (int) round($size[0] * $height / $size[1]);

        // A column of width w is about 7w + 5 pixels wide
        $tableWidth = array_sum(array_map(fn ($w) => $w * 7 + 5, $widths));
        if ($tableWidth < $width) {
            $extra = ($width - $tableWidth) / 7 / count($widths);
            $widths = array_map(fn ($w) => (int) ceil($w + $extra), $widths);
        }

        $drawing = new Drawing;
        $drawing->setName('Letterhead')->setDescription('Department of Agriculture MIMAROPA Region')
            ->setPath($file)->setResizeProportional(false)->setWidth($width)->setHeight($height)
            ->setCoordinates('A1')->setOffsetX(2)->setOffsetY(4)
            ->setWorksheet($ws);
        // Row heights are in points (3/4 of a pixel)
        $ws->getRowDimension(1)->setRowHeight(($height + 10) * 0.75);
    }

    private function setCell(Worksheet $ws, int $col, int $row, mixed $value, bool $money): void
    {
        if ($value === null || $value === '') {
            return;
        }
        if ($value instanceof CarbonInterface) {
            $ws->setCellValue([$col, $row], ExcelDate::PHPToExcel($value->copy()->startOfDay()));
            $ws->getStyle([$col, $row])->getNumberFormat()->setFormatCode('mmm d, yyyy');

            return;
        }
        if (is_int($value) || is_float($value)) {
            $ws->setCellValue([$col, $row], $value);
            if ($money) {
                $ws->getStyle([$col, $row])->getNumberFormat()->setFormatCode('#,##0.00');
            }

            return;
        }
        // Text typed into the system (names, purposes) is always written as text, never as a formula
        $ws->setCellValueExplicit([$col, $row], (string) $value, DataType::TYPE_STRING);
    }

    /** A writable temp file inside storage/ (the Windows/Herd system temp is not always writable) */
    private function tempFile(): string
    {
        $dir = storage_path('app/report-exports');
        if (! is_dir($dir)) {
            mkdir($dir, 0775, true);
        }
        foreach (glob($dir.DIRECTORY_SEPARATOR.'gss*') ?: [] as $old) {
            if (is_file($old) && filemtime($old) < time() - 3600) {
                @unlink($old);
            }
        }

        return $dir.DIRECTORY_SEPARATOR.'gss'.bin2hex(random_bytes(6));
    }
}
